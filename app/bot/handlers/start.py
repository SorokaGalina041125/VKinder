from app.bot.keyboards import get_main_keyboard

def handle_start(vk, user, send_msg_func):
    """Обработка команды старт"""
    message = (
        f"Привет, {user.first_name}! 👋\n\n"
        "🤖 Я помогу найти интересных людей для знакомств.\n\n"
        "🔍 **Поиск** — найду анкеты по твоим критериям\n"
        "➡️ **Следующий** — покажу следующую анкету\n"
        "⭐ **В избранное** — сохранить анкету\n"
        "🚫 **В чёрный список** — больше не показывать\n"
        "📋 **Избранное** — посмотреть список\n"
        "⛔ **Чёрный список** — посмотреть список\n\n"
        "🔄 **Новый поиск** — сбросить все критерии и настроить заново\n"
        "✏️ **Изменить критерии** — изменить отдельно пол, возраст или город\n\n"
        "👉 Нажми **Поиск**, чтобы начать!"
    )
    send_msg_func(vk, user.vk_id, message, get_main_keyboard())